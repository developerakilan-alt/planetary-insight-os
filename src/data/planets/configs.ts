export function getPlanetConfig(bodyId: BodyId): PlanetVisualConfig {
  return PLANET_CONFIGS[bodyId];
}

export function textureUrl(
  config: PlanetVisualConfig,
  stem: string,
  tier: string,
  source?: { ext?: string; single?: boolean },
): string {
  if (source?.single) return `/textures/${config.planetId}/${stem}.${source.ext ?? "jpg"}`;
  return `/textures/${config.planetId}/${stem}_${tier}.${source?.ext ?? "jpg"}`;
}

